// The themes as stored in the settings (the first three keep their old numbers).
enum ThemeId { ThemeLight = 0, ThemeDark = 1, ThemeSystem = 2, ThemeAmoled = 3, ThemeModernLight = 4, ThemeMidnight = 5, ThemeGraphite = 6, ThemeCount = 7 };
inline Palette paletteFor(int theme, bool systemDark) {
    switch (theme) {
        case ThemeDark: return darkPalette();
        case ThemeSystem: return systemDark ? darkPalette() : lightPalette();
        case ThemeAmoled: return amoledPalette();
        case ThemeModernLight: return modernLightPalette();
        case ThemeMidnight: return midnightPalette();
        case ThemeGraphite: return graphitePalette();
        default: return lightPalette();
    }
}

inline Palette& pal() { static Palette p = lightPalette(); return p; }

// A colour between two (t = 0: a, t = 1: b).
inline COLORREF mixColour(COLORREF a, COLORREF b, double t) {
    auto m = [t](int x, int y) { return static_cast<BYTE>(x + (y - x) * t + 0.5); };
    return RGB(m(GetRValue(a), GetRValue(b)), m(GetGValue(a), GetGValue(b)), m(GetBValue(a), GetBValue(b)));
}
// Relative luminance (WCAG), 0 to 1.
inline double luminance(COLORREF c) {
    auto ch = [](int v) { const double x = v / 255.0; return x <= 0.03928 ? x / 12.92 : std::pow((x + 0.055) / 1.055, 2.4); };
    return 0.2126 * ch(GetRValue(c)) + 0.7152 * ch(GetGValue(c)) + 0.0722 * ch(GetBValue(c));
}
inline double contrast(COLORREF a, COLORREF b) {
    const double la = luminance(a), lb = luminance(b);
    return (std::max(la, lb) + 0.05) / (std::min(la, lb) + 0.05);
}

// Paints into an off-screen bitmap and copies it to the window in one go, so nothing flickers.
struct PaintBuf {
    HDC target, dc;
    HBITMAP bmp, old;
    RECT clip;
    PaintBuf(HDC t, const RECT& client, const RECT& clipRect) : target(t), clip(clipRect) {
        dc = CreateCompatibleDC(t);
        bmp = CreateCompatibleBitmap(t, client.right > 0 ? client.right : 1, client.bottom > 0 ? client.bottom : 1);
        old = static_cast<HBITMAP>(SelectObject(dc, bmp));
        SelectClipRgn(dc, nullptr);
    }
    void done() {
        BitBlt(target, clip.left, clip.top, clip.right - clip.left, clip.bottom - clip.top, dc, clip.left, clip.top, SRCCOPY);
        SelectObject(dc, old);
        DeleteObject(bmp);
        DeleteDC(dc);
    }
};
